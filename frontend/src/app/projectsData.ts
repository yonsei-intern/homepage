export function buildProjectData(raw: string): ProjectItem[] {
  const lines = raw
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean);

  let year = "";
  const items: ProjectItem[] = [];

  for (const line of lines) {
    if (/^\d{4}$/.test(line)) {
      year = line;
      continue;
    }

    const parts = line.split("|");
    const title = parts[0]?.trim() ?? "";
    const organization = parts[1]?.trim() ?? "";
    if (!year || !title) continue;

    items.push({
      id: `proj-${year}-${items.length + 1}`,
      year,
      title,
      organization,
    });
  }

  return items;
}
