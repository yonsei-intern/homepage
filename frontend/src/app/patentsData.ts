const CATEGORY_LABEL: Record<PatentCategory, string> = {
  INTERNATIONAL_REGISTERED: "국제 특허 등록",
  INTERNATIONAL_FILED: "국제 특허 출원",
  DOMESTIC_REGISTERED: "국내 특허 등록",
  DOMESTIC_FILED: "국내 특허 출원",
  SW_OUTPUT: "SW 연구성과물",
};

export function patentCategoryLabel(category: PatentCategory): string {
  return CATEGORY_LABEL[category];
}

export function buildPatentData(raw: string): PatentItem[] {
  const lines = raw
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean);

  let category: PatentCategory | null = null;
  const items: PatentItem[] = [];

  for (const line of lines) {
    const section = line.match(/^\[(.+)\]$/);
    if (section) {
      category = section[1] as PatentCategory;
      continue;
    }

    if (!category) continue;
    const bar = line.indexOf("|");
    if (bar === -1) continue;

    const code = line.slice(0, bar).trim();
    const title = line.slice(bar + 1).trim();
    if (!code || !title) continue;

    items.push({
      id: `pat-${category}-${items.length + 1}`,
      code,
      title,
      category,
    });
  }

  return items;
}
